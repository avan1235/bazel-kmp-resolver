package org.jetbrains.kmp.resolver

import com.github.ajalt.clikt.command.SuspendingCliktCommand
import com.github.ajalt.clikt.core.CliktError
import com.github.ajalt.clikt.core.Context
import com.github.ajalt.clikt.parameters.groups.provideDelegate
import com.github.ajalt.clikt.parameters.options.option
import com.github.ajalt.clikt.parameters.options.required
import com.github.ajalt.clikt.parameters.types.path
import kotlin.io.path.inputStream
import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.SerializationException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.decodeFromStream

/**
 * Command that checks a pinned manifest against the resolution inputs it is expected to be
 * generated from, without resolving anything: it fails when the manifest follows another schema, or
 * when it was generated from other inputs, telling it is stale and must be generated again.
 */
class CheckBazelManifestCommand : SuspendingCliktCommand("check-bazel-manifest") {
    private val inputs by ResolutionInputsOptions()

    private val manifestFile by
        option(
                "--manifest-file",
                help = "Path to the manifest to check, written by generate-bazel-manifest.",
            )
            .path(mustExist = true, canBeDir = false, mustBeReadable = true)
            .required()

    override fun help(context: Context): String =
        "Checks that a manifest was generated by generate-bazel-manifest from the given resolution inputs and follows the schema of this resolver, exiting with a non-zero status when it does not."

    @OptIn(ExperimentalSerializationApi::class)
    override suspend fun run() {
        val header =
            try {
                manifestFile.inputStream().use { input ->
                    json.decodeFromStream<BazelManifestHeader>(input)
                }
            } catch (e: SerializationException) {
                throw CliktError("$manifestFile is not a manifest: ${e.message}", cause = e)
            }
        val inputsHash = inputs.manifestInputs().hash()
        when {
            header.schemaVersion != SCHEMA_VERSION ->
                throw CliktError(
                    "$manifestFile follows schema version ${header.schemaVersion}, while this resolver reads and writes schema version $SCHEMA_VERSION: generate it again with generate-bazel-manifest",
                )

            header.inputsHash != inputsHash ->
                throw CliktError(
                    "$manifestFile is stale: its inputsHash ${header.inputsHash} is not the hash $inputsHash of the given resolution inputs, generate it again with generate-bazel-manifest",
                )

            else ->
                echo(
                    "$manifestFile is up to date (inputsHash $inputsHash, generated by resolver ${header.resolverVersion})",
                )
        }
    }

    companion object {
        private val json = Json {
            ignoreUnknownKeys = true
        }
    }
}
